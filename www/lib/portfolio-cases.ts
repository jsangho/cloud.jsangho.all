/**
 * 프로젝트 상세(케이스) 데이터 — `/cases/<slug>`.
 *
 * 첫 화면(`app/page.tsx`)은 카드 두 장으로 끝나서 **무엇을 어떻게 만들었는지**를
 * 담을 자리가 없었다. 이 모듈이 그 자리다.
 *
 * 🔴 **적힌 수치는 전부 실측이다.** 측정한 날을 함께 적는 이유는 그 숫자가 늙기
 * 때문이다 — 날짜 없는 수치는 언제 맞았던 값인지 알 수 없어 검증이 불가능하다.
 * 실측하지 않은 값은 **적지 않는다.** 모르는 칸을 그럴듯한 숫자로 채우지 않는다.
 *
 * SUPER-SUB 쪽 사실의 출처는 이 저장소가 아니다 — 팀 저장소(`super-sub.cloud`)의
 * `agent/`(담당 영역)와 한이음 결과보고서다. 여기서 재측정할 수 없는 값은
 * 그 보고서가 실측으로 적은 값을 옮긴 것이고, 옮긴 날은 2026-10-06이다.
 */

export type CaseFact = {
  label: string;
  value: string;
  /** 분모·조건·측정일. **분모 없는 백분율을 쓰지 않는다** (DESIGN.md §14). */
  note?: string;
};

/** 거부한 것과 그 이유. 이 페이지의 알맹이다 — 만든 것보다 안 만든 것이 설계다. */
export type CaseDecision = { title: string; body: string };

export type CaseStackGroup = { group: string; items: readonly string[] };

export type CaseStudy = {
  slug: string;
  name: string;
  tagline: string;
  period: string;
  /** 혼자 만든 게 아닐 때만. 비우면 개인 작업으로 읽힌다. */
  role?: {
    team: string;
    mine: string;
    members: readonly { name: string; part: string }[];
  };
  /**
   * 출품한 대회. 혼자 만든 것이거나 어디에도 안 낸 것은 비운다.
   *
   * 🔴 **`result` 는 비울 수 없다**: 대회 이름만 적고 이 칸을 빼면 읽는 사람은
   * 수상했다고 읽는다. 그 자리를 채우는 것이 이 칸의 일이다.
   *
   * 다만 **못 받은 상을 굳이 적지는 않는다** (2026-10-07 사용자). 「출품」은
   * 그 자체로 완결된 답이다 — 냈다는 사실을 말하고 상을 주장하지 않는다.
   * 「수상하지 않았습니다」까지 적는 것은 사실을 더하는 게 아니라 같은 사실을
   * 스스로 깎아 말하는 것이다. **단, 받지 않은 상을 적지 않는다는 규칙은
   * 그대로다** — 여기에 쓸 수 있는 것은 실제로 도달한 단계뿐이다.
   *
   * **링크는 두지 않는다** (2026-10-07 사용자 결정). 대회 공고·이벤트
   * 페이지는 끝나면 내려가고, 그러면 포트폴리오에 죽은 링크가 남는다.
   * 이름·주최·일정을 글자로 적어 두면 링크 없이도 검증할 수 있다.
   */
  contest?: {
    name: string;
    host: string;
    /** 대회 일정. **프로젝트 기간과 다르다** — 둘을 섞지 않는다. */
    schedule: string;
    /** 어디까지 갔는지. 수상하지 않았으면 그대로 적는다. */
    result: string;
    /** 결과가 아직 확정이 아닐 때, 언제 기준의 상태인지. */
    resultNote?: string;
  };
  /**
   * 이 프로젝트를 직접 볼 수 있는 곳.
   *
   * 🔴 **`label` 은 URL 이 아니라 동사다** (2026-10-07). 전에는 주소 자체가
   * 레이블이라 12px 모노스페이스가 읽어야 할 글자였다 — 사용자가 "너무 작아
   * 보기 쉽지 않다"고 했고, 원인은 크기보다 **무엇을 누르는 버튼인지 글자가
   * 말하지 않는 것**이었다. 주소는 `href` 에서 뽑아 아래에 작게 깐다.
   *
   * `primary` 는 **페이지당 하나만** 둔다 — 골드는 이 시스템의 단일 액션
   * 색이고 퍼뜨리면 뜻이 사라진다 (DESIGN.md §7).
   */
  links: readonly { href: string; label: string; note?: string; primary?: boolean }[];
  image: string;
  imageAlt: string;
  /** 왜 만들었나. 단락. */
  lede: readonly string[];
  facts: readonly CaseFact[];
  flows: readonly Flow[];
  decisions: readonly CaseDecision[];
  stack: readonly CaseStackGroup[];
  /** 아직 못 한 것·한계. **적어 두지 않으면 위의 전부가 과장이 된다.** */
  limits: readonly string[];
};

