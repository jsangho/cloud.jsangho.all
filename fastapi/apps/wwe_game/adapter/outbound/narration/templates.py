"""템플릿 뱅크 — **서술 문자열은 전부 여기에 있다** (하네스 §6).

`rule_narrator.py`에는 문장이 한 줄도 없다. 문구를 고치는 일과 고르는 규칙을 고치는 일이
서로를 건드리지 않게 하려는 배치다 — 카드 덱을 JSON으로 뺀 것과 같은 이유(§3-D19)이고,
다만 이쪽은 슬롯 문법이 파이썬 `format`이라 데이터 파일로 뺄 이득이 없어 모듈로 둔다.

**슬롯 문법**: `{player:이}` 처럼 포맷 스펙 자리에 조사를 적으면 받침을 보고 골라 준다
(`rule_narrator._JosaFormatter`). 조사가 필요 없으면 `{player}` 그대로 쓴다.

| 슬롯 | 출처 |
|---|---|
| `player` | `run.identity.name` |
| `rival` | 가장 뜨거운 대립 상대 (§3-D13 실존 이름) — **없을 수 있다** |
| `venue` · `crowd` | **무대 권역** — 평소 북미, 가끔 해외 투어 (§3-D14-1) |
| `move` | 플레이스타일 |
| `reaction` | 인기도 구간 |
| `title` | 그 주차에 걸린 벨트 |

`rival`·`title`이 없는 주차에는 그 슬롯을 쓰는 템플릿이 후보에서 빠진다. 그래서 각
비트마다 **대립 없이도 성립하는 문장을 최소 3개** 둔다 — 안 그러면 대립이 없는 커리어의
후보가 말라 §11-6 다양성 기준을 못 지킨다.

**모든 문장은 `venue`·`crowd`·`move`·`reaction` 중 하나를 반드시 쓴다.** 이 두 규칙은
`rule_narrator._validate_bank()`가 임포트 시점에 강제한다 — 문장을 추가할 때 지키기
쉬운 규칙이 아니라서, 어기면 앱이 뜨지 않게 해 두는 편이 낫다.

`{reaction}`은 그 자체가 "…했다"로 끝나는 절이다. `{reaction}.` · `{reaction}는` ·
`{reaction}고`로만 이어 붙인다.
"""

