"""생활비 — 돈이 마르는 곳 (하네스 §3-D89).

§3-D48이 *"돈의 소비처가 없다"*로 남긴 자리의 나머지다. §3-D80이 분기 목표에 값을
붙여 절반을 닫았지만, 잔액은 여전히 **쌓이기만** 했다 — 실측(60판)에서 `safe` 정책이
서른 해에 $17.6M을 남겼고 쓸 곳이 분기마다 한 번뿐이었다.

## 아무것도 사지 않는다

처음 생각한 것은 트레이너·재활이었다. **마모(`wear`)를 돈으로 되돌리는 안을 접었다** —
마모는 몸 상태일 뿐이라고 봤는데, 세어 보니 셋에 닿는다:

| 마모가 닿는 곳 | |
|---|---|
| 부상 확률 | `INJURY_WEAR_FACTOR = 2.5`로 곱해진다 |
| 부진 판정 | `career_end.standing_of`가 뺀다 |
| 몸값 | `contract_office`가 깎는다 |

곧 마모를 사는 것은 **판정을 사는 것**이고, §13-Q13이 두 번 겪은 사고가 정확히 그
모양이다(§3-D41 포함). 그래서 이 절은 **사는 것이 아니라 나가는 것**이다.

## 씀씀이는 이름값을 따라간다

생활비가 인기도를 따라 오르는 이유는 하나다 — **그래야 무소속이 위험해진다.** 수입은
계약이 끊기는 순간 끊기는데(인디 개런티만 남는다) 인기도는 천천히 식으므로(§3-D25),
정상에서 잘린 선수는 **씀씀이는 그대로인 채 벌이만 사라진다.** 그 구간이 "돈이 마르는
곳"이라는 §3-D48의 문장 그대로다.

수입에 비례시키지 않은 이유도 같다. 벌이의 몇 %를 떼면 그건 그냥 감봉이라, 무소속이
되는 순간 지출도 함께 사라져 긴장이 생기지 않는다.

## 빚은 만들지 않는다

잔액은 0에서 멈춘다. 마이너스를 허용하면 **새 축이 하나 생긴다** — 빚이 얼마부터
위험한지, 갚는 길은 무엇인지, 못 갚으면 어떻게 되는지가 전부 새 규칙이다. §3-D48이
물은 것은 "돈이 마르는가"이고, 0에서 멈추는 것으로 그 질문에는 답이 된다.

**잔액이 0이면 비싼 분기 목표가 목록에서 빠진다**(§3-D80) — 못 고르는 것이 곧 가난의
의미이고, 그 고리가 이 절의 값이다.
"""

from __future__ import annotations

from wwe_game.domain.entities.career_run import CareerRun

LIVING_BASE = 400
"""주당 기본 생활비(달러). 인기도 0이어도 나가는 몫 — 사람은 살아야 한다."""

LIVING_PER_POPULARITY = 78
"""인기도 1당 붙는 주당 생활비.

인기도 70이면 주 $5,860, 90이면 $7,420이다. **연 30만~39만 달러**쯤이고, 그 급의
주급(실측 최종 $24,130)에 견주면 4분의 1 남짓이 나간다 — 벌이를 지우지 않으면서
잔액이 무한히 쌓이지도 않는 폭이다.

이 값을 올리면 무소속 구간이 곧 파산이 되고, 내리면 §3-D48이 다시 열린다.
**바꾸면 반드시 `measure_balance.py`로 60판을 잰다.**
"""


def weekly_cost(run: CareerRun) -> int:
    """이번 주에 나가는 생활비. **끝난 커리어는 0이다.**

    인기도만 본다 — 계약·잔액을 보면 "돈이 없으면 덜 쓴다"가 되고, 그러면 이 규칙이
    스스로를 무력화한다.
    """
    if not run.is_active:
        return 0
    return LIVING_BASE + run.stats.popularity * LIVING_PER_POPULARITY


def settle(run: CareerRun) -> CareerRun:
    """한 주치 생활비를 뺀다. **0에서 멈춘다** — 빚은 만들지 않는다.

    `career_advance.settle_week`이 부르는 자리다. 밖에서 이 순서를 다시 적으면
    갈린다 — `measure_balance.py`가 같은 함수를 지나야 측정이 성립한다.
    """
    cost = weekly_cost(run)
    if cost <= 0:
        return run
    return run.evolve(money=max(0, run.money - cost))
